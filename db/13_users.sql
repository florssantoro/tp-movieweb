CREATE TABLE IF NOT EXISTS movies.users (
                              user_id       INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                              user_username varchar(50) NOT NULL,
                              user_name     varchar(100) not null,
                              user_email    varchar(255) not null,
                              CONSTRAINT pk_users PRIMARY KEY (user_id),
                              CONSTRAINT uq_users_username UNIQUE (user_username),
                              CONSTRAINT uq_users_email unique (user_email)
);

CREATE TABLE IF NOT EXISTS movies.movie_user (
                                   user_id  INT NOT NULL,
                                   movie_id INT NOT NULL,
                                   rating   SMALLINT,
                                   opinion  TEXT,
                                   CONSTRAINT pk_movie_user PRIMARY KEY (user_id, movie_id),
                                   CONSTRAINT fk_mu_user  FOREIGN KEY (user_id)  REFERENCES movies.users (user_id) ON DELETE CASCADE,
                                   CONSTRAINT fk_mu_movie FOREIGN KEY (movie_id) REFERENCES movies.movie (movie_id) ON DELETE CASCADE,
                                   CONSTRAINT ck_mu_rating CHECK (rating BETWEEN 1 AND 5)
);
